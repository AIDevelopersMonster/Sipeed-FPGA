#!/usr/bin/env python3
"""Build LAB-03.2 ROM separately from LAB-02. Existing boot.hex and boot_rom.v untouched."""
from pathlib import Path
from assemble import parse_lines, assemble_instruction, NOP, ROM_WORDS


def main() -> None:
    base = Path(__file__).resolve().parents[1]
    source = base / 'firmware' / 'lab03_boot.S'
    code, labels = parse_lines(source)
    if len(code) > ROM_WORDS:
        raise ValueError(f'LAB03 firmware exceeds {ROM_WORDS} words: {len(code)}')
    result = []
    for i, (line, tokens) in enumerate(code):
        try:
            result.append(assemble_instruction(tokens, i * 4, labels))
        except Exception as e:
            raise ValueError(f'{source}:{line}: {e}') from e
    binary = result + [NOP] * (ROM_WORDS - len(result))
    (base / 'firmware' / 'lab03_boot.hex').write_text(
        ''.join(f'{x:08x}\n' for x in binary), encoding='ascii', newline='\n')
    rom = ['// LAB-03.2 generated by tools/assemble_lab03.py; SPDX-License-Identifier: MIT',
           'module lab03_boot_rom(input wire clk, input wire [7:0] word_addr, output reg [31:0] rdata);',
           '  always @(posedge clk) begin', '    case (word_addr)']
    for i, word in enumerate(result):
        rom.append(f"      8'd{i}: rdata <= 32'h{word:08x};")
    rom += ["      default: rdata <= 32'h00000013;", '    endcase', '  end', 'endmodule', '']
    (base / 'rtl' / 'lab03_boot_rom.v').write_text('\n'.join(rom), encoding='ascii', newline='\n')
    print(f'LAB03_2_ASSEMBLE_PASS: {len(result)} instructions, 1024 B ROM, labels={len(labels)}')


if __name__ == '__main__':
    main()
