#!/usr/bin/env python3
"""Minimal, deterministic RV32I *subset* assembler for firmware/boot.S.

Not a substitute for binutils. It intentionally fails on unknown mnemonics.
Outputs boot.hex and synthesizable boot_rom.v, both in the same repository.
"""
from __future__ import annotations
import argparse
import re
from pathlib import Path

REG = {f'x{i}': i for i in range(32)}
REG.update({'zero':0,'ra':1,'sp':2,'gp':3,'tp':4,
            't0':5,'t1':6,'t2':7,'s0':8,'fp':8,'s1':9,
            'a0':10,'a1':11,'a2':12,'a3':13,'a4':14,'a5':15,'a6':16,'a7':17,
            's2':18,'s3':19,'s4':20,'s5':21,'s6':22,'s7':23,'s8':24,'s9':25,'s10':26,'s11':27,
            't3':28,'t4':29,'t5':30,'t6':31})
NOP = 0x00000013
ROM_WORDS = 256

def reg(s: str) -> int:
    if s not in REG:
        raise ValueError(f'unknown register: {s}')
    return REG[s]

def number(s: str) -> int:
    return int(s, 0)

def imm_signed(v: int, width: int) -> int:
    if not (-(1 << (width-1)) <= v < (1 << (width-1))):
        raise ValueError(f'immediate {v} is outside signed {width}-bit range')
    return v & ((1 << width)-1)

def rmem(s: str):
    m = re.fullmatch(r'(-?(?:0x[0-9a-fA-F]+|\d+))\(([A-Za-z0-9]+)\)', s)
    if not m:
        raise ValueError(f'expected offset(reg), got {s}')
    return number(m.group(1)), reg(m.group(2))

def assemble_instruction(tokens, pc, labels):
    op, *a = tokens
    if op == 'lui':
        rd, value = reg(a[0]), number(a[1]);
        if not (0 <= value < (1 << 20)): raise ValueError('lui 20-bit immediate out of range')
        return (value << 12) | (rd << 7) | 0x37
    if op in ('addi','andi','srli'):
        rd, rs1, imm = reg(a[0]), reg(a[1]), number(a[2])
        if op == 'srli':
            if not 0 <= imm <= 31: raise ValueError('srli shift count must be 0..31')
            funct3 = 5
        else:
            imm = imm_signed(imm,12)
            funct3 = {'addi':0,'andi':7}[op]
        return (imm << 20) | (rs1 << 15) | (funct3 << 12) | (rd << 7) | 0x13
    if op in ('sw','lw'):
        if op == 'lw':
            rd = reg(a[0]); off, base = rmem(a[1]); i = imm_signed(off,12)
            return (i << 20) | (base << 15) | (2 << 12) | (rd << 7) | 0x03
        src = reg(a[0]); off, base = rmem(a[1]); i = imm_signed(off,12)
        return ((i >> 5) << 25) | (src << 20) | (base << 15) | (2 << 12) | ((i & 31) << 7) | 0x23
    if op in ('beq','bne'):
        rs1,rs2=reg(a[0]),reg(a[1]); offset = labels[a[2]]-pc
        if offset % 2: raise ValueError('unaligned branch')
        b = imm_signed(offset,13)
        f3 = 0 if op == 'beq' else 1
        return (((b >> 12)&1)<<31)|(((b>>5)&63)<<25)|(rs2<<20)|(rs1<<15)|(f3<<12)|(((b>>1)&15)<<8)|(((b>>11)&1)<<7)|0x63
    if op == 'jal':
        rd=reg(a[0]); offset=labels[a[1]]-pc
        if offset % 2: raise ValueError('unaligned jal')
        j = imm_signed(offset,21)
        return (((j>>20)&1)<<31)|(((j>>1)&1023)<<21)|(((j>>11)&1)<<20)|(((j>>12)&255)<<12)|(rd<<7)|0x6f
    if op == 'jalr':
        rd=reg(a[0]); off,base=rmem(a[1]); i=imm_signed(off,12)
        return (i<<20)|(base<<15)|(rd<<7)|0x67
    raise ValueError(f'unsupported instruction: {op}')

def parse_lines(source: Path):
    instructions=[]; labels={}
    for line_no,line in enumerate(source.read_text(encoding='utf-8').splitlines(),1):
        line=line.split('#',1)[0].strip()
        if not line or line.startswith('.'): continue
        while ':' in line:
            label, line = line.split(':',1)
            label=label.strip()
            if not re.fullmatch(r'[A-Za-z_][A-Za-z_0-9]*',label): raise ValueError(f'bad label: {label}')
            if label in labels: raise ValueError(f'duplicate label: {label}')
            labels[label]=len(instructions)*4
            line=line.strip()
        if not line: continue
        tokens=[x for x in re.split(r'[\s,]+',line) if x]
        instructions.append((line_no,tokens))
    return instructions,labels

def main():
    base=Path(__file__).resolve().parents[1]
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source',type=Path,default=base/'firmware'/'boot.S')
    parser.add_argument('--words',type=int,default=ROM_WORDS)
    args=parser.parse_args()
    code,labels=parse_lines(args.source)
    if len(code)>args.words: raise ValueError('firmware exceeds the boot ROM capacity')
    result=[]
    for idx,(line_no,tokens) in enumerate(code):
        try: result.append(assemble_instruction(tokens, idx*4, labels))
        except Exception as exc: raise ValueError(f'{args.source}:{line_no}: {exc}') from exc
    binary=result+[NOP]*(args.words-len(result))
    (base/'firmware'/'boot.hex').write_text(''.join(f'{v:08x}\n' for v in binary),encoding='ascii',newline='\n')
    rom=['// Generated by tools/assemble.py; do not edit. SPDX-License-Identifier: MIT',
         'module boot_rom(input wire clk, input wire [7:0] word_addr, output reg [31:0] rdata);',
         '  always @(posedge clk) begin','    case (word_addr)']
    for i,v in enumerate(result): rom.append(f"      8'd{i}: rdata <= 32'h{v:08x};")
    rom += ["      default: rdata <= 32'h00000013;",'    endcase','  end','endmodule','']
    (base/'rtl'/'boot_rom.v').write_text('\n'.join(rom),encoding='ascii',newline='\n')
    print(f'ASSEMBLE PASS: {len(result)} instructions, {len(binary)*4} B ROM, labels={len(labels)}')
    return 0

if __name__=='__main__': raise SystemExit(main())
