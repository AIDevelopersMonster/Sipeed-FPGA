#!/usr/bin/env python3
"""LAB-03.4 v0.3: derive a 0-capable TB from the user's proven LAB-03.2 TB.

Never edits the source TB. Enforces unique anchors, preserves original
4 / repeated T / C / 1 / T scenario, and adds C / 0 / T before $finish.
The generated Verilog belongs in ignored build/, not under tests/.
"""
from __future__ import annotations

import argparse
import hashlib
import re
import sys
from pathlib import Path


class PatchError(ValueError):
    pass


def exactly_one(pattern: str, source: str, description: str) -> re.Match:
    hits = list(re.finditer(pattern, source, re.MULTILINE))
    if len(hits) != 1:
        raise PatchError(f'{description}: expected exactly one anchor, found {len(hits)}; original TB untouched')
    return hits[0]


def derive(original: str, sha256: str = '') -> str:
    # Windows input files commonly contain CRLF. Regex anchors below are
    # line-oriented; normalize *only the generated copy*, never the input file.
    original = original.replace('\r\n', '\n').replace('\r', '\n')
    if 'lab03_4_trace_0.txt' in original or 'LAB03_4_ZERO_UART_TRACE_RTL_PASS' in original:
        raise PatchError('Input TB already has a LAB-03.4 zero scenario; original TB untouched')
    if not re.search(r'\bmodule\s+tb_lab03_2_uart\s*;', original):
        raise PatchError('Expected module tb_lab03_2_uart not found')
    if not re.search(r'task\s+save_trace\s*\(', original):
        raise PatchError('Expected save_trace task not found')
    if not re.search(r'host_send\s*\(\s*"4"\s*\)', original) or not re.search(r'host_send\s*\(\s*"1"\s*\)', original):
        raise PatchError('Original command-4 and command-1 tests must be present')
    if len(re.findall(r'host_send\s*\(\s*"T"\s*\)', original)) != 3:
        raise PatchError('Expected three original T reads, preserve original test exactly')
    if 'LAB03_2_UART_TRACE_RTL_PASS' not in original:
        raise PatchError('Original LAB-03.2 PASS marker not found')
    case3 = exactly_one(
        r'^(?P<indent>[ \t]*)3\s*:\s*fd\s*=\s*\$fopen\s*\(\s*"build/lab03_2_trace_1\.txt"\s*,\s*"w"\s*\)\s*;[ \t]*$',
        original, 'trace output case 3',
    )
    indent = case3.group('indent')
    # Insert AFTER case 3. Keep legacy paths/branches/markers unchanged.
    p = case3.end()
    out = original[:p] + '\n' + indent + '4:fd=$fopen("build/lab03_4_trace_0.txt","w");' + original[p:]
    anchor = exactly_one(
        r'^(?P<indent>[ \t]*)save_trace\s*\(\s*start_trace\s*,\s*tx_count\s*,\s*3\s*\)\s*;[ \t]*$',
        out, 'final original trace save',
    )
    old_end = out.find('LAB03_2_UART_TRACE_RTL_PASS', anchor.end())
    if old_end == -1 or '$finish' not in out[old_end:]:
        raise PatchError('Could not locate original PASS marker and $finish after command 1')
    sp = anchor.group('indent')
    snippet = f'''\n{sp}// LAB-03.4 v0.3 additive scenario: C -> 0 -> T (all LEDs OFF).
{sp}// The original 4/T/T/C/1/T checks above are not changed.
{sp}start_trace=tx_count;
{sp}host_send("C");wait(tx_count==start_trace+2);
{sp}expected(start_trace,"C");expected(start_trace+1,8'h0a);
{sp}if(dut.trace_done || dut.trace_truncated || dut.trace_count!==0)
{sp}    $fatal(1,"LAB03_4: clear before command 0 failed");
{sp}start_trace=tx_count;
{sp}host_send("0");wait(tx_count==start_trace+4);
{sp}expected(start_trace,"L");expected(start_trace+1,"=");
{sp}expected(start_trace+2,"0");expected(start_trace+3,8'h0a);
{sp}if(led_n!==6'b111111)
{sp}    $fatal(1,"LAB03_4: command 0 did not turn all LEDs OFF");
{sp}if(!dut.trace_done || dut.trace_truncated || dut.trace_overlap)
{sp}    $fatal(1,"LAB03_4: command 0 trace incomplete or overlapping");
{sp}start_trace=tx_count;
{sp}host_send("T");wait(terminators==4);
{sp}if((tx_count-start_trace)<100 || (tx_count-start_trace)>4096)
{sp}    $fatal(1,"LAB03_4: bad zero trace length %0d",tx_count-start_trace);
{sp}save_trace(start_trace,tx_count,4);
{sp}$display("LAB03_4_ZERO_UART_TRACE_RTL_PASS: C, 0, T; L=0; six LEDs OFF; final bus LED_WRITE");
'''
    out = out[:anchor.end()] + snippet + out[anchor.end():]
    header = '// AUTOGENERATED for LAB-03.4 v0.3; DO NOT EDIT; SOURCE TB UNCHANGED; SHA256=' + sha256 + '\n'
    final = header + out
    # Fail closed if core proof points are no longer present.
    for token in ('lab03_2_trace_4.txt','lab03_2_trace_4_repeat.txt','lab03_2_trace_1.txt',
                  'lab03_4_trace_0.txt','LAB03_2_UART_TRACE_RTL_PASS','LAB03_4_ZERO_UART_TRACE_RTL_PASS'):
        if token not in final:
            raise PatchError(f'After patch, required TB token not found: {token}')
    if len(re.findall(r'host_send\s*\(\s*"T"\s*\)', final)) != 4:
        raise PatchError('Generated TB did not have exactly four T requests')
    return final


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description='Generate, never overwrite, a LAB-03.4 command-0 extension of the local LAB-03.2 testbench.')
    ap.add_argument('--source', type=Path, required=True)
    ap.add_argument('--out', type=Path, required=True)
    args = ap.parse_args(argv)
    try:
        if args.source.resolve() == args.out.resolve():
            raise PatchError('Source and output must differ')
        if 'build' not in args.out.resolve().parts:
            raise PatchError('Output must be under a build/ directory (source tree remains untouched)')
        data = args.source.read_bytes()
        sha = hashlib.sha256(data).hexdigest()
        result = derive(data.decode('utf-8-sig'), sha)
        args.out.parent.mkdir(parents=True, exist_ok=True)
        args.out.write_text(result, encoding='utf-8', newline='\n')
        if hashlib.sha256(args.source.read_bytes()).hexdigest() != sha:
            raise PatchError('Input testbench changed during derivation')
        print(f'LAB03_4_V03_TB_DERIVED_PASS: source_sha256={sha}, generated={args.out.resolve()}')
        return 0
    except (PatchError, FileNotFoundError, UnicodeDecodeError, OSError) as exc:
        print(f'LAB03_4_V03_TB_BLOCKED: {exc}', file=sys.stderr)
        return 1


if __name__ == '__main__':
    sys.exit(main())
