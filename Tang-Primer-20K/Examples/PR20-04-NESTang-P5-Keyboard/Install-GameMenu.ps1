# NESTang v0.4 / Tang Primer 20K Dock
# Reproducible game menu installer for Windows PowerShell 5.1 / PowerShell 7.
# Creates GAME.cmd and GAME.ps1; collects existing ROMs in games/.
# Does NOT download ROMs, program FPGA, or write Flash.
[CmdletBinding()]
param([string]$Root = $PSScriptRoot)

$ErrorActionPreference = 'Stop'
$Root = (Resolve-Path -LiteralPath $Root).Path
$gamesDir = Join-Path $Root 'games'
New-Item -ItemType Directory -Path $gamesDir -Force | Out-Null

# Collect only *.nes files from the NESTang root and the old NES_GAMES folder.
# Never overwrite a game with the same filename.
$moved = 0
$skipped = 0
foreach ($src in @($Root, (Join-Path $Root 'NES_GAMES'))) {
    if (-not (Test-Path -LiteralPath $src -PathType Container)) { continue }
    foreach ($rom in @(Get-ChildItem -LiteralPath $src -Filter '*.nes' -File)) {
        $dest = Join-Path $gamesDir $rom.Name
        if (Test-Path -LiteralPath $dest) {
            Write-Host "SKIP (already exists): $($rom.Name)"
            $skipped++
            continue
        }
        Move-Item -LiteralPath $rom.FullName -Destination $dest
        Write-Host "MOVED: $($rom.Name)"
        $moved++
    }
}

$gameMenu = @'
# Auto-generated by Install-GameMenu.ps1
$ErrorActionPreference = 'Stop'
$root = $PSScriptRoot
$exe = Join-Path $root 'NESTang-Keyboard.exe'
$games = Join-Path $root 'games'

while ($true) {
    Clear-Host
    Write-Host '======================================'
    Write-Host '       NESTang GAME SELECTOR'
    Write-Host '       Tang Primer 20K Dock'
    Write-Host '======================================'
    Write-Host ''

    if (-not (Test-Path -LiteralPath $exe -PathType Leaf)) {
        Write-Host 'ERROR: NESTang-Keyboard.exe not found in this folder.'
        Write-Host 'Copy the separately supplied keyboard loader next to GAME.cmd.'
        Read-Host 'Press Enter'
        break
    }

    $roms = @(Get-ChildItem -LiteralPath $games -Filter '*.nes' -File | Sort-Object Name)
    if ($roms.Count -eq 0) {
        Write-Host 'No NES games in games folder.'
        Read-Host 'Press Enter'
        break
    }

    for ($i = 0; $i -lt $roms.Count; $i++) {
        Write-Host (' {0}. {1}' -f ($i + 1), $roms[$i].Name)
    }
    Write-Host ''
    Write-Host ' Q. Exit'
    Write-Host ''
    $choice = Read-Host 'Select game number'
    if ($choice.Trim().ToUpperInvariant() -eq 'Q') { break }

    $number = 0
    if (-not [int]::TryParse($choice, [ref]$number) -or
        $number -lt 1 -or $number -gt $roms.Count) {
        Write-Host 'Invalid selection.'
        Read-Host 'Press Enter'
        continue
    }

    $rom = $roms[$number - 1]
    Write-Host ''
    Write-Host "Loading: $($rom.Name)"
    Write-Host 'ESC - exit game'
    Write-Host ''
    & $exe $rom.FullName
    Write-Host ''
    Read-Host 'Press Enter to return to menu'
}
'@

$gameCmd = @'
@echo off
cd /d "%~dp0"
where pwsh.exe >nul 2>nul
if errorlevel 1 (
    powershell.exe -NoProfile -ExecutionPolicy Bypass -File "%~dp0GAME.ps1"
) else (
    pwsh.exe -NoLogo -NoProfile -ExecutionPolicy Bypass -File "%~dp0GAME.ps1"
)
pause
'@

Set-Content -LiteralPath (Join-Path $Root 'GAME.ps1') -Value $gameMenu -Encoding UTF8
Set-Content -LiteralPath (Join-Path $Root 'GAME.cmd') -Value $gameCmd -Encoding ASCII

Write-Host ''
Write-Host "MENU FILES READY: $Root\GAME.cmd"
Write-Host ("ROMs in games/: " + @(Get-ChildItem -LiteralPath $gamesDir -Filter '*.nes' -File).Count)
Write-Host "Moved: $moved; skipped duplicates: $skipped"
if (-not (Test-Path -LiteralPath (Join-Path $Root 'NESTang-Keyboard.exe'))) {
    Write-Warning 'The menu was created, but NESTang-Keyboard.exe is missing. Copy it next to GAME.cmd before launching.'
}
Write-Host 'Double-click GAME.cmd to select a game.'
